import { describe, expect, it } from 'vitest'

import { isPublicAddress } from './netGuard'

describe('isPublicAddress', () => {
    it.each([
        '0.0.0.0',
        '0.1.2.3',
        '10.1.2.3',
        '100.64.0.1',
        '100.127.255.255',
        '127.0.0.1',
        '127.255.255.254',
        '169.254.169.254',
        '172.16.0.1',
        '172.31.255.255',
        '192.0.0.1',
        '192.168.1.1',
        '192.0.2.1',
        '198.18.0.1',
        '198.19.255.255',
        '198.51.100.7',
        '203.0.113.9',
        '224.0.0.1',
        '239.255.255.255',
        '240.0.0.1',
        '255.255.255.255',
        '::',
        '::1',
        'fc00::1',
        'fd12::1',
        'fe80::1',
        'febf::1',
        'ff02::1',
        '2001:db8::1',
        '::ffff:127.0.0.1',
        '::ffff:10.0.0.1',
        '::ffff:7f00:1',
        '::ffff:a00:1',
        '0:0:0:0:0:ffff:127.0.0.1',
        '64:ff9b::7f00:1',
        '64:ff9b::127.0.0.1',
        'not-an-ip',
        '',
        '256.1.1.1',
        '1.2.3',
        '8.8.8.8/8',
        '[::1]',
    ])('rejects %s', (ip) => {
        expect(isPublicAddress(ip)).toBe(false)
    })

    it.each([
        '8.8.8.8',
        '1.1.1.1',
        '93.184.216.34',
        '172.32.0.1',
        '100.63.255.255',
        '100.128.0.1',
        '198.17.255.255',
        '198.20.0.1',
        '2606:4700:4700::1111',
        '::ffff:8.8.8.8',
        '::ffff:808:808',
        '64:ff9b::808:808',
    ])('accepts %s', (ip) => {
        expect(isPublicAddress(ip)).toBe(true)
    })
})
